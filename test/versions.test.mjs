const CARGO_TOML = `[package]
name = "scribe-app"
version = "0.8.0"
edition = "2021"

[dependencies]
serde = { version = "1.0", features = ["derive"] }

[dev-dependencies]
version-check = "0.9"
`

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "aaa"
version = "0.8.0"

[[package]]
name = "scribe-app"
version = "0.8.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.210"
`

const PACKAGE_LOCK = `{
  "name": "app",
  "version": "0.8.0",
  "lockfileVersion": 3,
  "packages": {
    "": {
      "name": "app",
      "version": "0.8.0"
    },
    "node_modules/x": {
      "version": "0.8.0"
    }
  }
}
`

function tauriApp(dir) {
  mkdirSync(join(dir, 'app/src-tauri'), { recursive: true })
  writeFileSync(join(dir, 'app/package.json'), `${JSON.stringify({ name: 'app', version: '0.8.0' }, null, 2)}\n`)
  writeFileSync(join(dir, 'app/package-lock.json'), PACKAGE_LOCK)
  writeFileSync(join(dir, 'app/src-tauri/tauri.conf.json'), `${JSON.stringify({ productName: 'Scribe', version: '0.8.0' }, null, 2)}\n`)
  writeFileSync(join(dir, 'app/src-tauri/Cargo.toml'), CARGO_TOML)
  writeFileSync(join(dir, 'app/src-tauri/Cargo.lock'), CARGO_LOCK)
}

test('Cargo.toml: only the [package] version changes, not a dependency that says "version"', () => {
  const dir = tmp('cargo')
  tauriApp(dir)
  const path = join(dir, 'app/src-tauri/Cargo.toml')
  assert.equal(readVersion(path), '0.8.0')
  setVersion(path, '0.10.0')
  assert.equal(readFileSync(path, 'utf8'), CARGO_TOML.replace('version = "0.8.0"', 'version = "0.10.0"'))
})

test("Cargo.lock: only the crate's own entry changes, found by the name in the Cargo.toml beside it", () => {
  const dir = tmp('lock')
  tauriApp(dir)
  const path = join(dir, 'app/src-tauri/Cargo.lock')
  assert.equal(readVersion(path), '0.8.0')
  setVersion(path, '0.9.0')
  const text = readFileSync(path, 'utf8')
  assert.match(text, /name = "scribe-app"\nversion = "0\.9\.0"/)
  assert.match(text, /name = "aaa"\nversion = "0\.8\.0"/)
  assert.equal(text.replace('"scribe-app"\nversion = "0.9.0"', '"scribe-app"\nversion = "0.8.0"'), CARGO_LOCK)
})

test('package-lock.json: both places npm keeps the version, and no dependency', () => {
  const dir = tmp('npmlock')
  tauriApp(dir)
  const path = join(dir, 'app/package-lock.json')
  setVersion(path, '0.9.0')
  const json = JSON.parse(readFileSync(path, 'utf8'))
  assert.equal(json.version, '0.9.0')
  assert.equal(json.packages[''].version, '0.9.0')
  assert.equal(json.packages['node_modules/x'].version, '0.8.0')
})

test('a Tauri app in app/: apply finds every version file, and a release bumps them all', () => {
  const repo = makeRepo(tmp('tauri'), { version: '0.8.0' })
  tauriApp(repo)
  run(repo, 'git', ['add', '-A'])
  run(repo, 'git', ['commit', '-q', '-m', 'chore: the app'])
  run(KIT, 'node', ['apply.mjs', repo, '--vendored', '--vendored'])
  const config = JSON.parse(readFileSync(join(repo, '.release.json'), 'utf8'))
  const files = ['app/src-tauri/tauri.conf.json', 'app/src-tauri/Cargo.toml', 'app/src-tauri/Cargo.lock', 'app/package.json', 'app/package-lock.json']
  assert.deepEqual(config.versionFiles, files)
  run(repo, 'git', ['add', '-A'])
  run(repo, 'git', ['commit', '-q', '-m', 'chore: adopt release-kit'])
  run(repo, 'node', ['scripts/release-kit/release.mjs', '--baseline'])
  commit(repo, 'feat: dictate into any app')
  run(repo, 'node', ['scripts/release-kit/release.mjs'])
  run(repo, 'node', ['scripts/release-kit/release.mjs', '--verify-tag', 'v0.9.0'])
  for (const file of files) assert.equal(readVersion(join(repo, file)), '0.9.0', file)
  assert.equal(run(repo, 'git', ['status', '--porcelain']), '')
  assert.match(readFileSync(join(repo, 'CHANGELOG.md'), 'utf8'), /## 0\.9\.0 - \d{4}-\d{2}-\d{2}\n\n### New\n\n- Dictate into any app\n/)
})

